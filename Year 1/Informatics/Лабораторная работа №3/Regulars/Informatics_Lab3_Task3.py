import re

STOP_STEMS = {"котор", "как", "так", "сам", "мо", "тв", "тво", "св", "сво", "наш", "ваш", "эт", "одн", "кажд", "вс", "нич"}


def replace_case(text: str, case_number: int) -> str:
    pattern = re.compile(
        r'\b([А-Яа-яЁё]+)'
        r'(ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ей|ых|их|ому|ему|ую|юю|ым|им|ою|ею|ом|ем|ыми|ими)\b'
    )

    if case_number < 1:
        raise ValueError("номер вхождения должен быть ≥ 1")
    endings = {}
    for stem, ending in pattern.findall(text):
        if stem not in STOP_STEMS:
            endings.setdefault(stem, []).append(ending.lower())

    def replace(match: re.Match) -> str:
        stem, ending = match.group(1), match.group(2)
        forms = endings.get(stem, [])
        if len(forms) < 2 or len(forms) < case_number:
            return match.group()
        new_ending = forms[case_number - 1]
        return stem + (new_ending.upper() if ending.isupper() else new_ending)

    return pattern.sub(replace, text)



