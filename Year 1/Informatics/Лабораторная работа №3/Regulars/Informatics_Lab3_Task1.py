import re


def remove_repeats(text: str) -> str:
    # Регулярное выражение для поиска последовательных повторов слова
    pattern = r'\b(\w+)(\s+\1)+\b'

    # Заменяем найденное совпадение на одиночное вхождение слова (обратная ссылка \1)
    cleaned_text = re.sub(pattern, r'\1', text, flags=re.IGNORECASE)

    # Убираем лишние пробелы
    cleaned_text = re.sub(r'\s+', ' ', cleaned_text).strip()

    return cleaned_text


